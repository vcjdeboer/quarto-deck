/**
 * Embed the template files in `templates_bundle.ts`, so the model finds them
 * however swamp bundles the extension (no file reads relative to the module).
 *
 *   ~/.swamp/deno/deno run -A templates/build.ts
 *
 * `templates_test.ts` fails when the bundle and these files differ.
 * @module
 */
const here = new URL(".", import.meta.url).pathname;

/** Every template file, by path relative to `templates/`, sorted. */
export async function templateFiles(): Promise<Record<string, string>> {
  const out: Record<string, string> = {};
  for await (const d of Deno.readDir(here)) {
    if (!d.isDirectory) continue;
    for await (const f of Deno.readDir(`${here}${d.name}`)) {
      if (f.isFile && !f.name.startsWith(".")) {
        out[`${d.name}/${f.name}`] = await Deno.readTextFile(
          `${here}${d.name}/${f.name}`,
        );
      }
    }
  }
  return Object.fromEntries(
    Object.entries(out).sort(([a], [b]) => a < b ? -1 : 1),
  );
}

/** Source of `templates_bundle.ts`. */
export function bundleSource(files: Record<string, string>): string {
  return [
    "// Generated by templates/build.ts from templates/ — do not edit.",
    "// Run: ~/.swamp/deno/deno run -A templates/build.ts",
    "",
    "/** Template files by path relative to templates/. */",
    "export const TEMPLATE_FILES: Record<string, string> = " +
    JSON.stringify(files, null, 2) + ";",
    "",
  ].join("\n");
}

if (import.meta.main) {
  const src = bundleSource(await templateFiles());
  await Deno.writeTextFile(`${here}../templates_bundle.ts`, src);
  console.log(`templates_bundle.ts: ${src.length} bytes`);
}
